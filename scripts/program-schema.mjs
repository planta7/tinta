import ts from "typescript";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { format, resolveConfig } from "prettier";
import { writeFileSync, readFileSync } from "node:fs";

function save(path, contents) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== contents)
      throw new Error(`Stale generated schema/validator: ${path}`);
  } else writeFileSync(path, contents);
}

const program = ts.createProgram(["contracts/public-api.d.ts"], {
  strict: true,
  target: ts.ScriptTarget.ES2022,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile("contracts/public-api.d.ts");
const root = source.statements.find(
  (node) => ts.isInterfaceDeclaration(node) && node.name.text === "ProgramIR",
);
const definitions = {};
const ids = new Map();

function schema(type) {
  if (type.flags & ts.TypeFlags.StringLiteral) return { const: type.value };
  if (type.flags & ts.TypeFlags.NumberLiteral) return { const: type.value };
  if (type.flags & ts.TypeFlags.BooleanLiteral)
    return { const: type.intrinsicName === "true" };
  if (type.flags & ts.TypeFlags.String) return { type: "string" };
  if (type.flags & ts.TypeFlags.Number) return { type: "number" };
  if (type.flags & ts.TypeFlags.Boolean) return { type: "boolean" };
  if (type.isUnion())
    return {
      anyOf: type.types
        .filter((t) => !(t.flags & ts.TypeFlags.Undefined))
        .map(schema),
    };
  if (checker.isArrayType(type))
    return { type: "array", items: schema(checker.getTypeArguments(type)[0]) };
  if (type.flags & ts.TypeFlags.Undefined)
    throw new Error("Unexpected undefined");
  if (ids.has(type.id)) return { $ref: `#/$defs/${ids.get(type.id)}` };
  const name = `shape${ids.size + 1}`;
  ids.set(type.id, name);
  definitions[name] = {};
  const properties = {},
    required = [];
  for (const property of checker.getPropertiesOfType(type)) {
    properties[property.name] = schema(
      checker.getTypeOfSymbolAtLocation(property, root),
    );
    if (!(property.flags & ts.SymbolFlags.Optional))
      required.push(property.name);
  }
  if (!Object.keys(properties).length)
    throw new Error(`Unresolved type ${checker.typeToString(type)}`);
  definitions[name] = {
    type: "object",
    properties,
    required,
    additionalProperties: false,
  };
  return { $ref: `#/$defs/${name}` };
}

const rootSchema = schema(checker.getTypeAtLocation(root));
const output = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "Tinta closed program IR",
  ...rootSchema,
  $defs: definitions,
};
const formatting = await resolveConfig("packages/engine/src/index.ts");
save(
  "schemas/program.schema.json",
  await format(JSON.stringify(output), { ...formatting, parser: "json" }),
);
const ajv = new Ajv2020({
  strict: true,
  code: { source: true, esm: true },
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
});
const validate = ajv.compile(output);
save(
  "packages/engine/src/program-validator.js",
  "// Generated by scripts/program-schema.mjs using the pinned Ajv compiler.\n" +
    (await format(standaloneCode(ajv, validate), {
      ...formatting,
      parser: "babel",
    })),
);
save(
  "packages/engine/src/program-validator.d.ts",
  "// Generated validator boundary; semantic validation follows schema validation.\nexport default function validate(value: unknown): boolean;\n",
);
